import assert from 'node:assert/strict';
import {validateInsights,rankContent} from '../marketing/insights.js';
const sample={version:1,account:'bruner.instituto',checkedAt:'2026-09-28T12:00:00Z',period:'Últimos 30 días',accountMetrics:{views:0,followers:12},audience:{nonFollowerViews:50},viewDistribution:[{label:'Reels',value:50}],interactionDistribution:[],posts:[{url:'https://instagram.com/reel/TEST/',title:'Curso',text:'MOLDERIA',format:'Reel',publishedAt:'2026-09-01T12:00:00Z',views:null,interactions:3}],token:'must-not-persist'};
const clean=validateInsights(sample);
assert.equal(clean.accountMetrics.views,0);
assert.equal(clean.accountMetrics.viewers,null);
assert.equal(clean.posts[0].url,'https://www.instagram.com/p/TEST/');
assert.ok(!('token' in clean));
assert.throws(()=>validateInsights({...sample,account:'otra.cuenta'}));
assert.throws(()=>validateInsights({...sample,accountMetrics:{views:-1}}));
assert.throws(()=>validateInsights({...sample,accountMetrics:{views:'100'}}));
assert.throws(()=>validateInsights({...sample,audience:{followerViews:101}}));
assert.throws(()=>validateInsights({...sample,posts:[sample.posts[0],{...sample.posts[0],url:'https://instagram.com/p/TEST/?x=1'}]}));
assert.throws(()=>validateInsights({...sample,posts:[{...sample.posts[0],url:'javascript:alert(1)'}]}));
const rows=[...clean.posts,{...clean.posts[0],url:'https://instagram.com/p/ZERO/',text:'Institucional',views:0,interactions:0}];
assert.equal(rankContent(rows,'views')[0].views,0);
assert.equal(rankContent(rows,'interactions')[0].interactions,3);
assert.equal(rankContent(rows,'views','Moldería, Corte y Confección').length,1);
assert.equal(rankContent(rows,'views','unknown').length,1);
console.log('PASS: private insights validation, zero vs missing, URL safety, duplicate rejection and course/metric ranking.');
