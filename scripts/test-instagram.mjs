import assert from 'node:assert/strict';
import fs from 'node:fs';
import {detectCourses,instagramId,snapshotRecords,mergePublications} from '../marketing/instagram.js';
import {publicationStats} from '../marketing/activity.js';
assert.deepEqual(detectCourses('Curso de MOLDERIA y soldadura'),['Moldería, Corte y Confección','Soldadura']);
assert.deepEqual(detectCourses('Llegó el verano ❄️'),[]);
assert.deepEqual(detectCourses('Plomerías'),[]);
assert.equal(instagramId('https://www.instagram.com/bruner.instituto/reel/ABC/?x=1'),'ABC');
assert.equal(instagramId('https://example.com/reel/ABC/'),'');
const imported=snapshotRecords({posts:[{url:'https://instagram.com/reel/ABC/',text:'Soldadura',format:'Reel',publishedAt:'2026-09-01T01:00:00Z'}]});
assert.equal(imported[0].publishedDate,'2026-08-31');
const local={id:'test',kind:'content',state:'Publicado',platform:'Instagram',url:'https://www.instagram.com/p/ABC/?utm_source=test',publishedDate:'2026-09-02'};
assert.equal(mergePublications([local],imported).length,1);
assert.equal(mergePublications([local],imported)[0].publishedDate,'2026-08-31');
assert.equal(publicationStats(mergePublications([local],imported),'2026-09').total,0);
const actual=snapshotRecords(JSON.parse(fs.readFileSync('marketing/instagram-snapshot.json','utf8')));
assert.equal(actual.length,8);
assert.equal(new Set(actual.map(r=>instagramId(r.url))).size,8);
assert.equal(publicationStats(actual,'2026-09').instagram,8);
assert.equal(publicationStats(actual,'2026-09').courses,4);
assert.equal(actual.filter(r=>r.courseNames.length===0).length,4);
console.log('PASS: keyword matching, unknown courses, Argentina dates, canonical links, deduplication and verified September snapshot.');
